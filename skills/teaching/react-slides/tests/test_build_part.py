import json

import pytest

import build_part
import manifest
import tsx_writer
from conftest import replace

TEMPLATE_FILES = {
    "package.json": '{"name": "course-slides", "version": "1.0.0"}\n',
    "src/components/x.ts": "export const x = 1;\n",
    "src/course.ts": "placeholder\n",
    "src/vocabulary.ts": "placeholder\n",
    "src/a.test.ts": "test\n",
    "src/b.test.tsx": "test\n",
    "src/__fixtures__/f.tsx": "fixture\n",
    "node_modules/junk/index.js": "junk\n",
    "dist/index.html": "built\n",
}


@pytest.fixture
def fake_template(tmp_path):
    root = tmp_path / "template"
    for rel, text in TEMPLATE_FILES.items():
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(text, encoding="utf-8")
    return root


def _run(course, parts, template, **kwargs):
    return build_part.run(course, parts, template_dir=template, skip_install=kwargs.pop("skip_install", True), **kwargs)


def _bump(template, version):
    (template / "package.json").write_text(json.dumps({"name": "course-slides", "version": version}) + "\n", encoding="utf-8")


def test_template_files_skip_what_the_app_must_not_get(fake_template):
    assert sorted(build_part.template_files(fake_template)) == ["package.json", "src/components/x.ts"]


def test_first_run_scaffolds_and_converts(course, fake_template):
    report = _run(course, [1], fake_template)
    web = course / "web"
    assert (web / "src/parts/part-01.tsx").exists() and (web / "src/parts/part-01.data.ts").exists()
    assert (web / "src/vocabulary.ts").read_text(encoding="utf-8").startswith("// Generated by react-slides")
    assert "สร้าง AI agent" in (web / "src/course.ts").read_text(encoding="utf-8")
    assert not (web / "node_modules").exists() and not (web / "src/a.test.ts").exists() and not (web / "dist").exists()
    assert report["install"] == "skipped" and report["stale"] == [] and report["parts"] == [1]
    assert "src/course.ts" in report["written"] and "src/components/x.ts" in report["written"]
    assert manifest.load(web).template_version == "1.0.0"
    assert "src/course.ts" not in manifest.load(web).files


def test_second_run_changes_nothing(course, fake_template):
    _run(course, [1], fake_template)
    report = _run(course, [1], fake_template)
    assert report["written"] == [] and "src/parts/part-01.tsx" in report["unchanged"]


def test_course_ts_is_never_overwritten(course, fake_template):
    _run(course, [1], fake_template)
    (course / "web/src/course.ts").write_text("export const course = { slug: 'x', title: 'mine' };\n", encoding="utf-8")
    _run(course, [1], fake_template)
    assert "mine" in (course / "web/src/course.ts").read_text(encoding="utf-8")


def test_visuals_use_content_keys(course, fake_template):
    report = _run(course, [1], fake_template)
    keys = [v["key"] for v in report["visuals"]]
    assert len(keys) == 3 and len(set(keys)) == 2  # the two identical descriptions share a key
    assert json.loads((course / "web/_work/part-01/visuals.json").read_text(encoding="utf-8")) == report["visuals"]
    shot = next(v for v in report["visuals"] if v["kind"] == "screenshot")
    assert shot["path"] == f"src/assets/images/part-01/{shot['key']}.png" and shot["exists"] is False
    drawn = next(v for v in report["visuals"] if v["kind"] == "illustration")
    assert drawn["path"] == f"src/illustrations/part-01/{drawn['key']}.tsx" and drawn["prompt"].startswith("A friendly robot")


def test_renumbered_deck_keeps_keys(course, fake_template):
    first = _run(course, [1], fake_template)["visuals"]
    key = first[0]["key"]
    (course / f"web/src/illustrations/part-01/{key}.tsx").parent.mkdir(parents=True)
    (course / f"web/src/illustrations/part-01/{key}.tsx").write_text("export default function X() { return null; }\n", encoding="utf-8")
    deck = course / "slides/part-01-first-agent.md"
    deck.write_text(deck.read_text(encoding="utf-8").replace("1-0", "1-1"), encoding="utf-8")
    again = _run(course, [1], fake_template)["visuals"]
    assert [v["key"] for v in again] == [v["key"] for v in first]
    assert [v["slide"] for v in again][0] == "1-101"
    assert all(v["exists"] for v in again if v["key"] == key)


def test_image_counts_as_present_for_an_illustration(course, fake_template):
    key = _run(course, [1], fake_template)["visuals"][0]["key"]
