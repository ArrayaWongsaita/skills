def test_unused_assets_are_reported_not_deleted(course, fake_template):
    stray = course / "web/src/illustrations/part-01/deadbeef.tsx"
    stray.parent.mkdir(parents=True)
    stray.write_text("old\n", encoding="utf-8")
    report = _run(course, [1], fake_template)
    assert report["unused"] == ["src/illustrations/part-01/deadbeef.tsx"] and stray.exists()


def test_converting_part_two_leaves_part_one_untouched(course, fake_template):
    _run(course, [1], fake_template)
    before = (course / "web/src/parts/part-01.tsx").read_bytes()
    report = _run(course, [2], fake_template)
    touched = report["written"] + report["unchanged"] + report["skipped"]
    assert "src/parts/part-01.tsx" not in touched and (course / "web/src/parts/part-01.tsx").read_bytes() == before
    assert report["stale"] == [2] and any("stale" in warning for warning in report["warnings"])


def test_unsupported_markup_is_a_warning(course, fake_template):
    report = _run(course, [1], fake_template)
    assert any("1-017" in warning and "~~" in warning for warning in report["warnings"])


def test_edited_part_is_skipped_and_reported(course, fake_template):
    _run(course, [1], fake_template)
    tsx = course / "web/src/parts/part-01.tsx"
    tsx.write_text(tsx.read_text(encoding="utf-8") + "// mine\n", encoding="utf-8")
    report = _run(course, [1], fake_template)
    assert set(report["skipped"]) == {"src/parts/part-01.tsx", "src/parts/part-01.data.ts"}
    assert "// mine" in tsx.read_text(encoding="utf-8")
    assert "-// mine" in report["diffs"]["src/parts/part-01.tsx"]


def test_force_path_is_normalised_or_refused(course, fake_template):  # Review Focus 5
    _run(course, [1], fake_template)
    tsx = course / "web/src/parts/part-01.tsx"
    tsx.write_text("// mine\n", encoding="utf-8")
    with pytest.raises(build_part.BuildError, match="skipped files: src/parts/part-01.data.ts, src/parts/part-01.tsx"):
        _run(course, [1], fake_template, force=frozenset({"src/nope.ts"}))
    report = _run(course, [1], fake_template, force=frozenset({"web\\src\\parts\\part-01.tsx"}))
    assert report["forced"] == ["src/parts/part-01.tsx"] and tsx.read_text(encoding="utf-8").startswith("// Generated")


def test_force_on_the_unedited_member_overwrites_the_pair(course, fake_template):
    _run(course, [1], fake_template)
    data = course / "web/src/parts/part-01.data.ts"
    data.write_text("// mine\n", encoding="utf-8")
    replace(course / "slides/part-01-first-agent.md", "**Title:** สรุป", "**Title:** สรุปทั้งหมด")
    report = _run(course, [1], fake_template, force=frozenset({"src/parts/part-01.tsx"}))
    assert report["forced"] == ["src/parts/part-01.data.ts"] and report["skipped"] == []
    assert data.read_text(encoding="utf-8").startswith("// Generated")
    assert "สรุปทั้งหมด" in (course / "web/src/parts/part-01.tsx").read_text(encoding="utf-8")


