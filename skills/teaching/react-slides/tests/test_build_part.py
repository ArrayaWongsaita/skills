def test_template_upgrade_replaces_only_unedited_files(course, fake_template):
    _run(course, [1], fake_template)
    (course / "web/src/components/x.ts").write_text("export const x = 'mine';\n", encoding="utf-8")
    _bump(fake_template, "1.1.0")
    (fake_template / "src/components/x.ts").write_text("export const x = 2;\n", encoding="utf-8")
    (fake_template / "src/components/y.ts").write_text("export const y = 1;\n", encoding="utf-8")
    report = _run(course, [1], fake_template)
    assert "src/components/x.ts" in report["skipped"] and "src/components/y.ts" in report["written"]
    assert "package.json" in report["written"] and report["template_version"] == "1.1.0"
    assert manifest.load(course / "web").template_version == "1.1.0"


def test_major_upgrade_regenerates_every_part(course, fake_template):
    _run(course, None, fake_template)
    _bump(fake_template, "2.0.0")
    report = _run(course, [1], fake_template)
    assert report["parts"] == [1, 2]


def test_older_parts_are_reported(course, fake_template, monkeypatch):
    _run(course, None, fake_template)
    monkeypatch.setattr(tsx_writer, "GENERATOR_VERSION", tsx_writer.GENERATOR_VERSION + 1)
    report = _run(course, [1], fake_template)
    assert report["older_parts"] == [2]


def test_package_json_change_needs_install(course, fake_template):
    assert _run(course, [1], fake_template)["install"] == "skipped"
    (course / "web/node_modules").mkdir()
    assert _run(course, [1], fake_template)["install"] == "not-needed"
    _bump(fake_template, "1.0.1")
    assert _run(course, [1], fake_template)["install"] == "skipped"


def test_cli_exit_codes(course, fake_template, capsys, monkeypatch):
    monkeypatch.setattr(build_part, "TEMPLATE_DIR", fake_template)
    assert build_part.main([str(course), "1", "--skip-install"]) == 0
    assert json.loads(capsys.readouterr().out)["parts"] == [1]
    replace(course / "slides/part-01-first-agent.md", "### 1-006 · explain", "### 1-006 · fancy")
    assert build_part.main([str(course), "--all", "--skip-install"]) == 1
    err = capsys.readouterr().err
    assert "error: slides/part-01-first-agent.md: line " in err and "unknown layout fancy" in err


def test_missing_npm_is_a_clear_error(course, fake_template, monkeypatch, tmp_path):
    monkeypatch.setenv("PATH", str(tmp_path / "empty"))
    with pytest.raises(build_part.BuildError, match="install Node.js 20 or later"):
        _run(course, [1], fake_template, skip_install=False)
    assert not (course / "web").exists()
