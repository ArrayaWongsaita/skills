def test_illustration_gets_its_key(course):
    out = tsx_writer.part_tsx(deck_reader.load(course, 1), 1)
    key = hashlib.sha256("หุ่นยนต์ผู้ช่วยถือกล่องเครื่องมือ".encode()).hexdigest()[:8]
    assert out.count(f'"key": "{key}"') == 2


def test_data_ts_holds_listings_and_outputs(course):
    data = tsx_writer.part_data_ts(deck_reader.load(course, 1), 1)
    assert '"status": "unverified"' in data and '"info": "text illustrative"' in data and "export const meta" in data
    assert "import type" in data and '"slug": "part-01"' in data


def test_data_ts_keeps_only_typed_diagram_keys(course):
    path = course / "slides" / "part-01-first-agent.md"
    path.write_text(path.read_text(encoding="utf-8").replace('"canvas": [16, 8],', '"canvas": [16, 8], "extra": 1,'), encoding="utf-8")
    data = tsx_writer.part_data_ts(deck_reader.load(course, 1), 1)
    body = data.split("export const diagrams: Record<string, DiagramDef> = ", 1)[1].split(";\n", 1)[0]
    assert "extra" not in json.loads(body)["d-agent-loop"]


def test_vocabulary_and_course_ts(course):
    vocabulary = deck_reader.read_vocabulary(course)
    out = tsx_writer.vocabulary_ts(vocabulary)
    assert "export const vocabulary: Vocabulary = " in out and '"icon": "bot"' in out and "added_in" not in out
    assert tsx_writer.course_ts("c", 'ชื่อ "x"') .endswith('export const course = { slug: "c", title: "ชื่อ \\"x\\"" };\n')
