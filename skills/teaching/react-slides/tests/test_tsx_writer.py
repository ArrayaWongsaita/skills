def test_slides_in_a_unit_carry_it(course):
    tsx = tsx_writer.part_tsx(deck_reader.load(course, 1), 1)
    assert 'unit="u-run-agent"' in tsx and "units={units}" in tsx
    slide = lambda sid: tsx.split(f'id="{sid}"')[1].split("\n      />")[0]
    assert 'unit="u-declare-tool"' in slide("1-014")  # inherits the topic before it
    assert "unit=" not in slide("1-018") and "unit=" not in slide("1-003")  # after an assembly, and in the opening


def test_units_travel_as_data(course):  # Review Focus 5
    replace(course / DECK, '"title": "เรียก agent"', '"title": "a {b} <c>"')
    replace(course / DECK, "**Title:** เรียก agent", "**Title:** a {b} <c>")
    loaded = deck_reader.load(course, 1)
    assert '"title": "a {b} <c>"' in tsx_writer.part_data_ts(loaded, 1)
    assert "a {b} <c>" not in tsx_writer.part_tsx(loaded, 1).replace('{"a {b} <c>"}', "")


def test_units_data_keeps_only_render_keys(course):
    replace(course / DECK, '"needs": [\n            "u-declare-tool"\n          ]', '"needs": [\n            "u-declare-tool"\n          ],\n          "moved_from": "1.3",\n          "reason": "r"')
    data = tsx_writer.part_data_ts(deck_reader.load(course, 1), 1)
