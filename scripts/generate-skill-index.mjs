#!/usr/bin/env node
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const indexPath = path.join(repoRoot, "docs", "skills", "README.md");
const source = "ArrayaWongsaita/skills";

function parseFrontmatter(markdown, file) {
  const match = markdown.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) {
    throw new Error(`${file} must start with YAML frontmatter`);
  }

  const fields = {};
  for (const line of match[1].split("\n")) {
    const field = line.match(/^([a-z][a-z0-9_-]*):\s*(.*)$/i);
    if (!field) {
      throw new Error(`${file} has invalid frontmatter line: ${line}`);
    }
    fields[field[1]] = field[2].trim();
  }

  return fields;
}

async function directoryEntries(directory) {
  return readdir(directory, { withFileTypes: true });
}

export async function discoverSkills(root = repoRoot) {
  const skillRoot = path.join(root, "skills");
  const categories = (await directoryEntries(skillRoot))
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("."))
    .sort((a, b) => a.name.localeCompare(b.name));
  const skills = [];

  for (const category of categories) {
    const categoryPath = path.join(skillRoot, category.name);
    const skillEntries = (await directoryEntries(categoryPath))
      .filter((entry) => entry.isDirectory() && !entry.name.startsWith("."))
      .sort((a, b) => a.name.localeCompare(b.name));

    for (const skill of skillEntries) {
      const skillFile = path.join(categoryPath, skill.name, "SKILL.md");
      const markdown = await readFile(skillFile, "utf8");
      const metadata = parseFrontmatter(markdown, skillFile);

      skills.push({
        category: category.name,
        name: skill.name,
        metadataName: metadata.name ?? "",
        description: metadata.description ?? "",
        skillPath: path.posix.join("skills", category.name, skill.name),
        guidePath: path.posix.join("docs", "skills", category.name, `${skill.name}.md`),
      });
    }
  }

  return skills;
}

function tableText(value) {
  return value.replaceAll("|", "\\|").replaceAll(/\s+/g, " ").trim();
}

function installCommand(skills) {
  const names = skills.map((skill) => skill.name);
  if (names.length === 1) {
    return `npx skills add ${source} --skill ${names[0]}`;
  }

  return [
    `npx skills add ${source} \\`,
    ...names.map((name, index) => `  --skill ${name}${index === names.length - 1 ? "" : " \\"}`),
  ].join("\n");
}

export function renderIndex(skills) {
  const categories = [...new Set(skills.map((skill) => skill.category))];
  const lines = [
    "# Skill Index / ดัชนี Skill",
    "",
    "> Generated by `npm run docs:index`. Do not edit this file manually.",
    "> สร้างโดย `npm run docs:index` ไม่ควรแก้ไฟล์นี้ด้วยมือ",
    "",
    "This index is grouped by the repository's primary category. / ดัชนีนี้แบ่งตามหมวดหลักของ repo",
    "",
    "## Install every skill / ติดตั้งทุก skill",
    "",
    `\`\`\`bash\nnpx skills add ${source} --all\n\`\`\``,
    "",
  ];

  for (const category of categories) {
    const categorySkills = skills.filter((skill) => skill.category === category);
    lines.push(`## ${category} / หมวด ${category}`, "");
    lines.push("| Skill | Description / คำอธิบาย | Guide / คู่มือ |", "| --- | --- | --- |");

    for (const skill of categorySkills) {
      const guide = `${skill.category}/${skill.name}.md`;
      lines.push(`| \`${skill.name}\` | ${tableText(skill.description)} | [คู่มือ / Guide](${guide}) |`);
    }

    lines.push(
      "",
      "### Install this category / ติดตั้งทั้งหมวด",
      "",
      `\`\`\`bash\n${installCommand(categorySkills)}\n\`\`\``,
      "",
    );
  }

  if (categories.length === 0) {
    lines.push("No skills have been added yet. / ยังไม่มี skill ใน repo นี้", "");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

export async function generateIndex(root = repoRoot) {
  const skills = await discoverSkills(root);
  const outputPath = path.join(root, "docs", "skills", "README.md");
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, renderIndex(skills), "utf8");
  return { outputPath, skills };
}

const currentFile = fileURLToPath(import.meta.url);
if (process.argv[1] && path.resolve(process.argv[1]) === currentFile) {
  const { outputPath, skills } = await generateIndex();
  console.log(`generated ${path.relative(repoRoot, outputPath)} for ${skills.length} skill(s)`);
}
